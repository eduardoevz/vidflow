import type {
  AudioFormat,
  MediaFormat,
  MediaInfo,
  SubtitleTrack,
  VideoFormat,
} from '../../../shared/media-types';
import type { YtDlpFormatJson, YtDlpInfoJson } from './ytDlpJson';

function protocolFor(format: YtDlpFormatJson): MediaFormat['protocol'] {
  const proto = format.protocol ?? '';
  if (proto.includes('m3u8')) return 'hls';
  if (proto.includes('dash')) return 'dash';
  if (proto.startsWith('https')) return 'https';
  if (proto.startsWith('http')) return 'http';
  return 'direct';
}

function toResolutionLabel(height?: number | null): string | undefined {
  if (!height) return undefined;
  return `${height}p`;
}

function normalizeFormat(raw: YtDlpFormatJson): MediaFormat | undefined {
  if (!raw.url) return undefined;

  const hasVideo = Boolean(raw.vcodec && raw.vcodec !== 'none');
  const hasAudio = Boolean(raw.acodec && raw.acodec !== 'none');
  const filesizeBytes = raw.filesize ?? raw.filesize_approx ?? undefined;
  const filesizeIsEstimate = !raw.filesize && Boolean(raw.filesize_approx);

  const base = {
    formatId: raw.format_id,
    extension: raw.ext,
    protocol: protocolFor(raw),
    url: raw.url,
    bitrateKbps: raw.tbr ?? undefined,
    filesizeBytes,
    filesizeIsEstimate,
    audioOnly: hasAudio && !hasVideo,
    videoOnly: hasVideo && !hasAudio,
    hasAudio,
    hasVideo,
  };

  if (hasVideo) {
    const videoFormat: VideoFormat = {
      ...base,
      kind: 'video',
      width: raw.width ?? undefined,
      height: raw.height ?? undefined,
      resolutionLabel: toResolutionLabel(raw.height),
      fps: raw.fps ?? undefined,
      videoCodec: raw.vcodec ?? undefined,
      audioCodec: raw.acodec ?? undefined,
    };
    return videoFormat;
  }

  if (hasAudio) {
    const audioFormat: AudioFormat = {
      ...base,
      kind: 'audio',
      audioCodec: raw.acodec ?? undefined,
      sampleRateHz: raw.asr ?? undefined,
    };
    return audioFormat;
  }

  return undefined;
}

function normalizeSubtitles(info: YtDlpInfoJson): SubtitleTrack[] {
  const tracks: SubtitleTrack[] = [];
  const collect = (
    map: Record<string, { url: string; name?: string }[]> | undefined,
    isAuto: boolean,
  ) => {
    if (!map) return;
    for (const [lang, entries] of Object.entries(map)) {
      const first = entries[0];
      if (!first) continue;
      tracks.push({
        language: lang,
        label: first.name ?? lang,
        url: first.url,
        isAutoGenerated: isAuto,
      });
    }
  };
  collect(info.subtitles, false);
  collect(info.automatic_captions, true);
  return tracks;
}

export function normalizeMediaInfo(raw: YtDlpInfoJson): MediaInfo {
  const formats = (raw.formats ?? [])
    .map(normalizeFormat)
    .filter((f): f is MediaFormat => f !== undefined);

  return {
    metadata: {
      title: raw.title,
      author: raw.uploader ?? undefined,
      channel: raw.channel ?? undefined,
      durationSeconds: raw.duration ?? undefined,
      thumbnailUrl: raw.thumbnail ?? undefined,
      uploadDate: raw.upload_date ?? undefined,
      siteName: raw.extractor_key ?? 'unknown',
      originalUrl: raw.webpage_url ?? '',
    },
    formats,
    subtitles: normalizeSubtitles(raw),
    isLive: Boolean(raw.is_live),
    extractor: 'yt-dlp',
  };
}
