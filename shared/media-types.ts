/** Normalized media model — the UI (and IPC layer) never sees raw yt-dlp JSON. */

export type MediaProtocol = 'https' | 'http' | 'hls' | 'dash' | 'direct';

export interface SubtitleTrack {
  language: string;
  label: string;
  url: string;
  isAutoGenerated: boolean;
}

interface BaseFormat {
  formatId: string;
  extension: string;
  protocol: MediaProtocol;
  url: string;
  bitrateKbps?: number;
  filesizeBytes?: number;
  /** true when filesizeBytes is an approximation (common for HLS/DASH manifests) */
  filesizeIsEstimate: boolean;
  audioOnly: boolean;
  videoOnly: boolean;
  hasAudio: boolean;
  hasVideo: boolean;
}

export interface VideoFormat extends BaseFormat {
  kind: 'video';
  width?: number;
  height?: number;
  resolutionLabel?: string; // e.g. "1080p"
  fps?: number;
  videoCodec?: string;
  audioCodec?: string;
}

export interface AudioFormat extends BaseFormat {
  kind: 'audio';
  audioCodec?: string;
  sampleRateHz?: number;
}

export type MediaFormat = VideoFormat | AudioFormat;

export interface MediaMetadata {
  title: string;
  author?: string;
  channel?: string;
  durationSeconds?: number;
  thumbnailUrl?: string;
  uploadDate?: string;
  siteName: string;
  originalUrl: string;
  referer?: string;
}

export interface AnalysisOptions {
  referer?: string;
}

export interface MediaInfo {
  metadata: MediaMetadata;
  formats: MediaFormat[];
  subtitles: SubtitleTrack[];
  isLive: boolean;
  extractor: 'yt-dlp' | 'generic' | 'manifest';
}

export interface PlaylistEntry {
  id: string;
  title: string;
  url: string;
  durationSeconds?: number;
  thumbnailUrl?: string;
  author?: string;
}

export interface PlaylistInfo {
  id?: string;
  title: string;
  author?: string;
  originalUrl: string;
  entries: PlaylistEntry[];
}

export type AnalysisErrorCode =
  | 'invalid_url'
  | 'unsupported_site'
  | 'private_video'
  | 'auth_required'
  | 'protected_content'
  | 'extractor_outdated'
  | 'network_error'
  | 'unknown';

export interface AnalysisError {
  code: AnalysisErrorCode;
  message: string;
  suggestion?: string;
}

export type QualityPreset =
  | 'best'
  | 'best_1080p'
  | 'best_720p'
  | 'smallest'
  | 'audio_only';
